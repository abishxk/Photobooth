export function getDailyNote(): string {
  const today = new Date().toDateString();
  const storageKey = 'retromatica_daily_note';

  try {
    const stored = localStorage.getItem(storageKey);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (parsed.date === today) return parsed.note;
    }
  } catch (_) { /* ignore */ }

  const historyKey = 'retromatica_note_history';
  let history: string[] = [];
  try {
    const h = localStorage.getItem(historyKey);
    if (h) history = JSON.parse(h);
    if (history.length > 365) history = history.slice(-365);
  } catch (_) { /* ignore */ }

  const available = notes.filter(n => !history.includes(n));
  const pool = available.length > 0 ? available : notes;
  const note = pool[Math.floor(Math.random() * pool.length)];

  try {
    localStorage.setItem(storageKey, JSON.stringify({ date: today, note }));
    history.push(note);
    localStorage.setItem(historyKey, JSON.stringify(history));
  } catch (_) { /* ignore */ }

  return note;
}

